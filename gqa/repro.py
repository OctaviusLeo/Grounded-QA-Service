"""Reproducibility helper shared by every result-emitting script (Req 0.1, 0.2, 0.4).

Every reported number carries a :class:`Stamp`: the exact command that produced it, the integer
seed, and the full 40-character commit hash of the code that ran. A stamp is only meaningful if
the code was committed, so :func:`make_stamp` refuses to stamp a dirty working tree. Generated
output paths are excluded from that check, because the scripts themselves write them.
"""

from __future__ import annotations

import json
import re
import shlex
import subprocess
import sys
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

# Paths that scripts write; changes there do not make the code under test differ from the commit.
GENERATED_PREFIXES = ("results/", "docs/media/", ".kiro/")

_HASH_RE = re.compile(r"^[0-9a-f]{40}$")


class ReproError(RuntimeError):
    """The commit or working tree cannot support a reproducible stamp."""


@dataclass(frozen=True)
class Stamp:
    command: str
    seed: int
    commit: str

    def __post_init__(self) -> None:
        if not _HASH_RE.match(self.commit):
            raise ReproError(f"commit must be a 40-character lowercase hex hash, got {self.commit!r}")
        if isinstance(self.seed, bool) or not isinstance(self.seed, int):
            raise ReproError(f"seed must be an integer, got {self.seed!r}")


def _git(repo: Path, *args: str) -> str:
    proc = subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, text=True, check=False
    )
    if proc.returncode != 0:
        raise ReproError(f"git {' '.join(args)} failed: {proc.stderr.strip()}")
    return proc.stdout


def commit_hash(repo: str | Path = ".") -> str:
    """Return the full 40-character hash of HEAD."""
    value = _git(Path(repo), "rev-parse", "HEAD").strip()
    if not _HASH_RE.match(value):
        raise ReproError(f"unexpected output from git rev-parse HEAD: {value!r}")
    return value


def dirty_paths(repo: str | Path = ".") -> list[str]:
    """Return modified or untracked paths, excluding generated output paths."""
    out = _git(Path(repo), "--no-optional-locks", "status", "--porcelain", "--untracked-files=all")
    paths = []
    for line in out.splitlines():
        if not line.strip():
            continue
        path = line[3:]
        if " -> " in path:  # rename: "old -> new"
            path = path.split(" -> ", 1)[1]
        path = path.strip('"')
        if not path.startswith(GENERATED_PREFIXES):
            paths.append(path)
    return paths


def require_clean_tree(repo: str | Path = ".") -> None:
    """Raise :class:`ReproError` naming every uncommitted source path."""
    dirty = dirty_paths(repo)
    if dirty:
        listed = ", ".join(dirty[:20]) + (" ..." if len(dirty) > 20 else "")
        raise ReproError(
            f"refusing to stamp results: {len(dirty)} uncommitted path(s): {listed}. Commit first."
        )


def current_command(argv: list[str] | None = None) -> str:
    """The command line that started this process, as a copy-pasteable string."""
    args = list(sys.argv if argv is None else argv)
    spec = getattr(sys.modules.get("__main__"), "__spec__", None)
    if argv is None and spec is not None and spec.name != "__main__":
        # Started as `python -m <module>`: argv[0] is the module's file path.
        return "python -m " + shlex.join([spec.name.removesuffix(".__main__"), *args[1:]])
    if args and args[0].endswith(".py"):
        path = Path(args[0])
        try:
            path = path.resolve().relative_to(Path.cwd().resolve())
        except ValueError:
            pass
        args[0] = path.as_posix()
        return "python " + shlex.join(args)
    return shlex.join(args)


def make_stamp(
    seed: int,
    command: str | None = None,
    repo: str | Path = ".",
    require_clean: bool = True,
) -> Stamp:
    """Build the stamp for a result produced by the current process."""
    if require_clean:
        require_clean_tree(repo)
    return Stamp(command=command or current_command(), seed=seed, commit=commit_hash(repo))


def stamp_to_dict(stamp: Stamp) -> dict[str, Any]:
    return asdict(stamp)


def stamp_from_dict(data: dict[str, Any]) -> Stamp:
    return Stamp(command=str(data["command"]), seed=data["seed"], commit=str(data["commit"]))


def stamp_markdown(stamp: Stamp) -> str:
    """One line that sits in the same section as the numbers it covers."""
    return f"Generated by `{stamp.command}` · seed `{stamp.seed}` · commit `{stamp.commit}`"


def write_json(path: str | Path, payload: dict[str, Any], stamp: Stamp) -> None:
    """Write ``payload`` plus its stamp as stable, LF-terminated JSON."""
    body = dict(payload)
    body["stamp"] = stamp_to_dict(stamp)
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(body, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")


def read_stamped_json(path: str | Path) -> tuple[dict[str, Any], Stamp]:
    """Read a file written by :func:`write_json`; the stamp is validated."""
    body = json.loads(Path(path).read_text(encoding="utf-8"))
    stamp = stamp_from_dict(body.pop("stamp"))
    return body, stamp
